// Draws text as one bitmap, with a one-pixel gap between glyphs.
export function textBitmap(text: string): Bitmap {
  const rows = Array<string>(GLYPH_HEIGHT).fill('');
  [...text.toUpperCase()].forEach((char, index) => {
    const glyph = (GLYPHS[char] ?? GLYPHS['?']).split('|');
    glyph.forEach((row, y) => {
      rows[y] += (index > 0 ? '.' : '') + row;
    });
  });
  return rows;
}

export function bitmapWidth(bitmap: Bitmap): number {
  return Math.max(0, ...bitmap.map((row) => row.length));
}

// Converts lit pixels into SVG path data, one rectangle per horizontal run.
export function bitmapPath(bitmap: Bitmap): string {
  let path = '';
  bitmap.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x += 1;
        continue;
      }
      let run = 0;
      while (row[x + run] === '#') {
        run += 1;
      }
      path += `M${x} ${y}h${run}v1h-${run}z`;
      x += run;
    }
  });
  return path;
}
